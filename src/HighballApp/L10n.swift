/// Highball 本地化映射层：内置简体中文 (zhHans)、繁體中文 (zhHant) 与法语 (fr)。
func L(_ en: String) -> String {
    let dict: [String: String]
    switch HighballLang.current {
    case .zhHans: dict = L10n.zhHans
    case .zhHant: dict = L10n.zhHant
    case .fr: dict = L10n.fr
    case .en: return en
    }
    if let hit = dict[en] { return hit }
    if en.hasPrefix("Starting "), let fmt = dict["Starting %@"] {
        return String(format: fmt, String(en.dropFirst("Starting ".count)))
    }
    if en.hasPrefix("Installing "), let fmt = dict["Installing %@"] {
        return String(format: fmt, String(en.dropFirst("Installing ".count)))
    }
    return en
}

